"""Turn findings into concrete, copy-paste upgrade guidance."""
from packaging.utils import canonicalize_name
from packaging.version import InvalidVersion, Version


def _parse(value):
    try:
        return Version(str(value))
    except InvalidVersion:
        return None


def suggest_upgrades(dependencies, findings):
    """Return one upgrade per vulnerable package.

    The target is the highest fixed version reported by OSV that is newer than
    the pinned version. Fixed versions that are not newer (for example a fix on
    an older release branch) are ignored.
    """
    best = {}
    for finding in findings:
        target = _parse(finding.get("fixed_version"))
        if target is None:
            continue
        key = canonicalize_name(finding["package"])
        if key not in best or target > best[key][0]:
            best[key] = (target, finding["fixed_version"])

    upgrades = []
    for dependency in dependencies:
        key = canonicalize_name(dependency["name"])
        current = _parse(dependency["version"])
        if key in best and current is not None and best[key][0] > current:
            upgrades.append({
                "package": dependency["name"],
                "current": dependency["version"],
                "target": best[key][1],
            })
    return upgrades


def build_fixed_requirements(dependencies, upgrades):
    """Render a requirements.txt using upgraded pins where available."""
    targets = {canonicalize_name(u["package"]): u["target"] for u in upgrades}
    lines = [
        "# Generated by SupplyShield AI - review and test before deploying.",
    ]
    for dependency in dependencies:
        version = targets.get(canonicalize_name(dependency["name"]), dependency["version"])
        lines.append(f"{dependency['name']}=={version}")
    return "\n".join(lines) + "\n"
